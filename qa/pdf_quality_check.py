#!/usr/bin/env python3
"""Independent Poppler extraction and pixel-level visual regression.
All files are synthetic and generated by this workflow; never customer data.
This test is not a substitute for manual Android QA or accessibility review.
"""
import json
import os
import subprocess
import unicodedata
from pathlib import Path
from PIL import Image, ImageChops, ImageStat

ROOT = Path("/tmp")
OUTPUT = Path("candidate/pdf-perf-visual")
OUTPUT.mkdir(parents=True, exist_ok=True)
variants = {
    "sections": [ROOT / "sirati-pdf-baseline", ROOT / "sirati-pdf-candidate"],
    "photo": [ROOT / "sirati-pdf-photo-baseline", ROOT / "sirati-pdf-photo-candidate"],
    "long": [ROOT / "sirati-pdf-long-baseline", ROOT / "sirati-pdf-long-candidate"],
}
pairs = []
for kind, (before, after) in variants.items():
    b = {v["id"]: v for v in json.loads((before / "results.json").read_text())}
    a = {v["id"]: v for v in json.loads((after / "results.json").read_text())}
    assert b and b.keys() == a.keys(), f"{kind}: unmatched test PDFs"
    for key in sorted(b):
        assert b[key]["pages"] == a[key]["pages"], f"{key}: changed page count"
        pairs.append((kind, key, before / (key + ".pdf"), after / (key + ".pdf"), a[key]["pages"]))

def command(*args):
    return subprocess.run(args, check=True, text=True, capture_output=True).stdout

def normalized(s):
    return unicodedata.normalize("NFC", s).replace("\u200e", "").replace("\u200f", "")

def raster(pdf, suffix, page=1, width=1240):
    prefix = OUTPUT / suffix
    command("pdftoppm", "-f", str(page), "-l", str(page),
            "-scale-to", str(width), "-png", "-singlefile",
            str(pdf), str(prefix))
    path = Path(str(prefix) + ".png")
    assert path.exists(), f"Poppler failed to render {pdf}"
    return Image.open(path).convert("RGB")

def compare(first, second, label):
    assert first.size == second.size, f"{label}: changed visible page dimensions"
    gray = ImageChops.difference(first, second).convert("L")
    stats = ImageStat.Stat(gray)
    mean_delta = stats.mean[0]
    hist = gray.histogram()
    changed_fraction = sum(hist[25:]) / (first.width * first.height)
    assert mean_delta <= 3.0, f"{label}: mean visual delta {mean_delta:.3f}"
    assert changed_fraction <= 0.06, f"{label}: excessive changed pixels {changed_fraction:.2%}"
    return {"mean_delta": round(mean_delta, 3),
            "fraction_changed_gt_25": round(changed_fraction, 6)}

def ink_ratio(image):
    return sum(ImageChops.difference(
        image, Image.new("RGB", image.size, (255, 255, 255))).convert("L")
        .histogram()[35:]) / (image.width * image.height)

reports = []
visuals = {
    "modern-en-1440", "modern-ar-390", "compact-ats-en-390",
    "profile-sidebar-en-1440", "gold-sidebar-ar-390",
    "executive-letterhead-en-390", "healthcare-pro-ar-1440",
    "classic-en-390", "executive-ats-en-1440",
    "photo-profile-sidebar-en-1440", "photo-gold-sidebar-ar-390",
    "long-en1", "long-en2", "long-ar3", "long-short"
}
for kind, key, before, after, pages in pairs:
    assert before.is_file() and after.is_file(), key + ": PDF missing"
    # Independent UTF-8 text extraction, in addition to the prior PDF.js checks.
    raw_before = normalized(command("pdftotext", "-raw", str(before), "-"))
    raw_after = normalized(command("pdftotext", "-raw", str(after), "-"))
    assert len(raw_after.strip()) > 25, f"{key}: Poppler found no selectable text"
    if kind == "sections":
        markers = (["SummaryMarker", "ExperienceMarker", "EducationMarker",
                    "CertificationMarker", "CourseMarker", "ProjectMarker",
                    "SkillsMarker", "LanguagesMarker"] if "-en-" in key else
                   ["ملخص", "خبرة", "درجة", "شهادة", "دورة",
                    "مشروع", "مهارات", "اللغة"])
        for marker in markers:
            assert marker in raw_after, f"{key}: independent pdftotext lost {marker}"
        for marker in markers:
            assert marker in raw_before, f"{key}: baseline pdftotext lost {marker}"
    elif kind == "long":
        marker = "الخبرة" if key == "long-ar3" else "Software" if key == "long-short" else "Professional"
        assert marker.casefold() in raw_after.casefold(), f"{key}: missing Poppler text"
    fonts=command("pdffonts",str(after))
    assert "yes" in fonts.lower(),f"{key}: missing embedded fonts"
    entry = {"id":key,"pages":pages,"poppler_unicode":True}
    if key in visuals:
        bimg = raster(before, "baseline-"+key)
        aimg = raster(after, "candidate-"+key)
        entry.update(compare(bimg,aimg,key))
        if kind=="long" and pages>1:
            tail=raster(after,"candidate-last-"+key,page=pages)
            assert ink_ratio(tail)>0.0005,f"{key}: near-blank trailing A4 page"
    reports.append(entry)
    print("PASS",key,"pages",pages,"Poppler UTF-8 extraction, fonts, visual gate" if key in visuals else "Poppler UTF-8 extraction")
assert len(reports)==48, f"Expected 36 section + 8 portrait + 4 long baseline comparisons, got {len(reports)}"
(OUTPUT/"quality-summary.json").write_text(json.dumps(reports,indent=2,ensure_ascii=False))
with open(os.environ["GITHUB_STEP_SUMMARY"],"a") as out:
    out.write("\n## Independent PDF quality gates\n")
    out.write(f"- {len(reports)} paired PDFs: native text via Poppler, embedded fonts, valid output\n")
    out.write(f"- {len(visuals)} sampled layout/portrait/long CV comparisons passed automated render-pixel thresholds\n")
    out.write("- Physical Android PDF viewer and independent human visual/ATS review remain unverified\n")
print("PASS: Poppler, embedded fonts, representative visual regression, nonblank long tail")
